#!/usr/bin/env node
// Assembles data.js and outputs.js from src/*.js, build/*.json and real/*. Deterministic.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const rd = (p) => fs.readFileSync(path.join(here, p), 'utf8');
const files = fs.readdirSync(path.join(here, 'src')).filter((f) => /^\d\d-.*\.js$/.test(f)).sort();
let body = '';
for (const f of files) {
  let t = rd('src/' + f);
  if (f === '00-head.js') { body += t.replace(/^\/\* Sleipnir Web[\s\S]*?\(function \(root\) \{\n'use strict';\n/, ''); continue; }
  t = t.replace('/*FILES_JSON*/', 'S.files = { shop: ' + rd('build/shop.json').trim() + ', orders: ' + rd('build/orders.json').trim() + ' };');
  t = t.replace(/\/\*REAL:([\w./-]+)\*\//g, (_, p) => JSON.stringify(JSON.parse(rd(p))));
  t = t.replace(/\/\*REALTEXT:([\w./-]+)\*\//g, (_, p) => JSON.stringify(rd(p)));
  body += '\n' + t;
}
const head = rd('src/00-head.js').match(/^\/\*[\s\S]*?\*\/\n\(function \(root\) \{\n'use strict';\n/)[0];
body = body.replace(/^[ \t]+/gm, '').replace(/\n{2,}/g, '\n');
const out = head + body + '\n})(typeof globalThis !== "undefined" ? globalThis : typeof window !== "undefined" ? window : this);\n';
// the mocks inline these files in a <script>: a literal </script or <!-- inside a string would end or confuse it
const safe = (t) => t.replaceAll('</script', '<\\/script').replaceAll('<!--', '<\\!--');
const outSafe = safe(out);
fs.writeFileSync(path.join(here, 'data.js'), outSafe);
console.log('data.js', Buffer.byteLength(outSafe), 'bytes from', files.length, 'modules');
// outputs.js
const ofiles = fs.existsSync(path.join(here, 'src/outputs')) ? fs.readdirSync(path.join(here, 'src/outputs')).filter((f) => /^\d\d-.*\.js$/.test(f)).sort() : [];
if (ofiles.length) {
  let ob = '/* Sleipnir Web, round 2: command outputs (outputs.js). Load after data.js. Generated by build.mjs from src/outputs/*.js. */\n(function (root) {\n\'use strict\';\nvar S = root.SLDATA;\nif (!S) throw new Error("outputs.js needs data.js first");\nvar F = S.fmt;\n';
  for (const f of ofiles) {
    let t = rd('src/outputs/' + f);
    t = t.replace(/\/\*REAL:([\w./-]+)\*\//g, (_, p) => JSON.stringify(JSON.parse(rd(p))));
    t = t.replace(/\/\*REALTEXT:([\w./-]+)\*\//g, (_, p) => JSON.stringify(rd(p)));
    ob += '\n' + t;
  }
  ob = ob.replace(/^[ \t]+/gm, '').replace(/\n{2,}/g, '\n');
  ob += '\n})(typeof globalThis !== "undefined" ? globalThis : typeof window !== "undefined" ? window : this);\n';
  fs.writeFileSync(path.join(here, 'outputs.js'), safe(ob));
  console.log('outputs.js', Buffer.byteLength(safe(ob)), 'bytes from', ofiles.length, 'modules');
}
